/**
 * A quad whose four vertices carry a per-corner DEPTH in the red channel,
 * which is what the water shader reads to decide colour and clarity. The
 * builder's own `quad` writes one colour for the whole face, so the
 * shallows and the middle of the pool would come out identical.
 *
 * The depth is pushed as a LINEAR colour triple directly, not through
 * `b.color()`: that runs an sRGB→linear table, which is right for
 * anything anybody looks at and wrong for a channel being used to carry
 * a number the shader will read back.
 */
function quadDepth(b, p0, p1, p2, p3, d0, d1, d2, d3) {
  const put = (p, d) => b.vert(p[0], p[1], p[2], 0, [clamp01(d), 0, 0]);
  const a = put(p0, d0), c = put(p1, d1), e = put(p2, d2), f = put(p3, d3);
  /* WOUND SO THE FACE LOOKS UP. The first version wound these the other
     way; the water material is a Lambert, Lambert is FrontSide, and a
     surface whose normal points at the bed is a surface nobody can see.
     The loading screen rendered a brown empty bowl for three rounds
     because of it, and it is exactly the kind of fault that no amount of
     reading the code finds and one look at the picture finds instantly. */
  b.tri(a, e, c);
  b.tri(a, f, e);
}
